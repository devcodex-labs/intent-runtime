const entries = Object.entries(translations).sort((a, b) => b[0].length - a[0].length);
export function english(value) {
  if (typeof value === 'string') {
    if (Object.hasOwn(translations, value)) return translations[value];
    for (const [source, target] of entries) value = value.replaceAll(source, target);
    if (/[\u3400-\u9fff]/u.test(value)) throw new Error('Missing English scenario translation: ' + value);
    return value;
  }
  if (Array.isArray(value)) return value.map(english);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, english(item)]));
  return value;
}
